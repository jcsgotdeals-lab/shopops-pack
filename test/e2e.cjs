const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1200, height: 900 }, acceptDownloads: true });
  const p = await ctx.newPage();
  const errors = [];
  p.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  p.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
  const shot = n => p.screenshot({ path: path.join(__dirname, 'shots', n + '.png'), fullPage: true });
  await p.goto('http://127.0.0.1:8765/');
  await p.waitForSelector('#new-show');
  await p.fill('#show-name', 'Friday toys LIVE');
  await p.click('#new-show button');
  await p.waitForSelector('#batch-form');
  await p.fill('#b-name', 'Toys');
  await p.fill('#b-count', '20');
  await shot('1-stickers');
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#batch-form button[type=submit]')]);
  await dl.saveAs(path.join(__dirname, 'out', dl.suggestedFilename()));
  console.log('stickers', dl.suggestedFilename());
  await p.goto('http://127.0.0.1:8765/#import');
  await p.setInputFiles('#pdf-input', path.join(__dirname, 'fixture-tiktok.pdf'));
  await p.waitForSelector('#commit-import', { timeout: 20000 });
  await shot('2-import');
  console.log('preview', await p.textContent('.stats.big'));
  await p.click('#commit-import');
  await p.waitForSelector('.tray-grid .tray-tile');
  console.log('trays', (await p.$$eval('.tray-tile', ts => ts.map(t => t.innerText.replace(/\n/g, ' | ')))));
  await shot('3-trays');
  const [dl2] = await Promise.all([p.waitForEvent('download'), p.click('#dl-labels')]);
  await dl2.saveAs(path.join(__dirname, 'out', dl2.suggestedFilename()));
  const [dl3] = await Promise.all([p.waitForEvent('download'), p.click('#dl-traylabels')]);
  await dl3.saveAs(path.join(__dirname, 'out', dl3.suggestedFilename()));
  await p.goto('http://127.0.0.1:8765/#scan');
  await p.waitForSelector('#scan-input');
  for (const c of ['TOY0007', 'TOY0001', 'TOY0001', 'TOY0099']) { await p.fill('#scan-input', c); await p.press('#scan-input', 'Enter'); await p.waitForTimeout(250); console.log('scan', c, '=>', (await p.innerText('#result')).replace(/\n/g, ' | ')); }
  await shot('4-scan');
  await p.goto('http://127.0.0.1:8765/#pack');
  await p.fill('#scan-input', 'TOY0002'); await p.press('#scan-input', 'Enter');
  await p.waitForSelector('.checklist');
  for (const c of ['TOY0003', 'TOY0001', 'TOY0002', 'TOY0008']) { await p.fill('#scan-input', c); await p.press('#scan-input', 'Enter'); await p.waitForTimeout(250); console.log('pack', c, '=>', (await p.innerText('#result')).replace(/\n/g, ' | ')); }
  await shot('5-pack');
  await p.goto('http://127.0.0.1:8765/#history?q=maria');
  await p.waitForTimeout(400);
  console.log('history rows', await p.$$eval('table tbody tr', r => r.length));
  await p.setViewportSize({ width: 390, height: 844 });
  await p.goto('http://127.0.0.1:8765/#trays');
  await p.waitForTimeout(400);
  await shot('6-phone-trays');
  await p.goto('http://127.0.0.1:8765/#scan'); await p.fill('#scan-input', 'TOY0005'); await p.press('#scan-input', 'Enter'); await p.waitForTimeout(300);
  await shot('7-phone-scan');
  console.log('overflow', await p.evaluate(() => document.documentElement.scrollWidth > innerWidth));
  console.log('ERRORS', errors);
  await b.close();
})();
